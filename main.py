"""Top-level orchestration for the multilingual sentiment experiment pipeline."""

import glob
import logging
import os
import random
from dataclasses import dataclass

import numpy as np
import pandas as pd
import torch

from SRC.ablation import run_neural_experiments
from SRC.baseline import run_baseline_model
from SRC.dataset import load_and_preprocess_data
from SRC.error_analysis import build_error_analysis_examples
from SRC.reporting import build_results_export_table
from SRC.reporting import build_results_table
from SRC.reporting import build_validation_results_table
from SRC.reporting import plot_layer_freezing_ablation
from SRC.reporting import plot_main_result_comparison
from SRC.reporting import plot_training_validation_loss


logging.basicConfig(level=logging.INFO, format="%(message)s")
for name in ["httpx", "httpcore", "urllib3", "requests", "huggingface_hub"]:
    logging.getLogger(name).setLevel(logging.ERROR)
for name in ["datasets", "transformers"]:
    logging.getLogger(name).setLevel(logging.ERROR)

SEEDS = [42, 43, 44]
DATASET_NAME = "neonwatty/amazon_reviews_multi"
MODEL_NAME = "bert-base-multilingual-cased"

TRAIN_SIZE = 5000
TEST_SIZES = {"en": 1000, "es": 1000, "ja": 1000}


MAX_LEN = 256
TRAIN_EPOCHS = 1
TRAIN_BATCH = 8
EVAL_BATCH = 8

CACHE_DIR = "./data"
TRANS_CACHE_DIR = "./data/translation_cache"
TRAIN_OUT_DIR = "./outputs"
PLOTS_DIR = "./plots"
CSV_DIR = "./outputs_csv"
TQDM_BAR = "{l_bar}{bar}| {n_fmt}/{total_fmt}"

@dataclass
class ExperimentMetric:
    """Container for one experiment-language metric row."""

    experiment_group: str
    experiment_name: str
    language: str
    accuracy: float
    f1: float
    train_samples: int
    test_samples: int


def _set_global_seed(seed):
    """Set Python/NumPy/Torch RNG seeds for deterministic experiment runs."""
    # Synchronize Python, NumPy, and Torch RNG states for one experiment pass.
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def _clear_old_plots():
    """Delete stale PNG plots so each run exports a clean figure set."""
    # Keep only plots generated by the current run.
    os.makedirs(PLOTS_DIR, exist_ok=True)
    for path in glob.glob(os.path.join(PLOTS_DIR, "*.png")):
        os.remove(path)


def _run_all_seeds():
    """Run baseline+neural experiments for all configured seeds and collect rows."""
    # pylint: disable=too-many-locals
    # Execute baseline + neural pipeline for each seed and collect raw outputs.
    seeds = SEEDS
    all_results = []
    all_error_rows = []
    best_logits_for_examples = None
    best_seed_for_examples = seeds[0]
    test_data_for_examples = None

    for seed in seeds:
        _set_global_seed(seed)
        train_data, test_data = load_and_preprocess_data(
            DATASET_NAME, seed, TRAIN_SIZE, TEST_SIZES, CACHE_DIR
        )
        logging.info(
            "Prepared samples (seed=%d): train=%d, en=%d, es=%d, ja=%d",
            seed,
            len(train_data),
            len(test_data["en"]),
            len(test_data["es"]),
            len(test_data["ja"]),
        )

        seed_metrics = []
        run_baseline_model(
            train_data,
            test_data,
            seed_metrics,
            ExperimentMetric,
            TRANS_CACHE_DIR,
            TQDM_BAR,
            logging,
        )

        seed_out_dir = os.path.join(TRAIN_OUT_DIR, f"seed_{seed}")
        best_logits, error_rows = run_neural_experiments(
            train_data,
            test_data,
            seed_metrics,
            ExperimentMetric,
            MODEL_NAME,
            MAX_LEN,
            TRAIN_EPOCHS,
            TRAIN_BATCH,
            EVAL_BATCH,
            seed,
            seed_out_dir,
            PLOTS_DIR,
            logging,
        )
        if seed == best_seed_for_examples:
            best_logits_for_examples = best_logits
            test_data_for_examples = test_data

        for metric in seed_metrics:
            row = dict(metric.__dict__)
            row["seed"] = seed
            all_results.append(row)
        for row in error_rows:
            out_row = dict(row)
            out_row["seed"] = seed
            all_error_rows.append(out_row)

    return (
        seeds,
        all_results,
        all_error_rows,
        best_logits_for_examples,
        test_data_for_examples,
    )


def _export_results(seeds, all_results, all_error_rows):
    """Build tables/plots and save the aggregated report CSV."""
    # Build result tables and plots, then save compact CSV output.
    summary_long = pd.DataFrame(all_results)
    summary_stats = build_results_table(summary_long, seeds)
    plot_main_result_comparison(summary_long, summary_stats, PLOTS_DIR)
    plot_layer_freezing_ablation(summary_stats, PLOTS_DIR)
    plot_training_validation_loss(all_error_rows, summary_long, seeds, PLOTS_DIR)

    summary_export = build_results_export_table(summary_stats)
    validation_table = build_validation_results_table(all_error_rows, seeds)
    if len(validation_table) > 0:
        summary_export = summary_export.merge(
            validation_table,
            on="experiment_name",
            how="left",
        )

    os.makedirs(CSV_DIR, exist_ok=True)
    stats_path = os.path.join(CSV_DIR, "results.csv")
    summary_export.to_csv(stats_path, index=False, encoding="utf-8")


def _export_error_examples(best_logits_for_examples, test_data_for_examples):
    """Export selected ES/JA qualitative error examples to CSV."""
    # Export fixed-size ES/JA error cases for report discussion.
    if best_logits_for_examples is None or test_data_for_examples is None:
        return
    error_df = build_error_analysis_examples(
        test_data_for_examples,
        best_logits_for_examples,
    )
    csv_path = os.path.join(CSV_DIR, "error_analysis_examples.csv")
    error_df.to_csv(csv_path, index=False, encoding="utf-8")


def main() -> None:
    """Entrypoint: run all configured experiments and export report artifacts."""
    # Run all experiments under multiple seeds and aggregate report-ready stats.
    os.makedirs(TRAIN_OUT_DIR, exist_ok=True)
    _clear_old_plots()

    (
        seeds,
        all_results,
        all_error_rows,
        best_logits_for_examples,
        test_data_for_examples,
    ) = _run_all_seeds()
    _export_results(seeds, all_results, all_error_rows)
    _export_error_examples(best_logits_for_examples, test_data_for_examples)
    logging.info("Pipeline completed successfully")


if __name__ == "__main__":
    main()
